"""Render Appendix A (exam vs current platform) from ``book/exam/platform-changes.yaml``."""

from db_ml_associate.content.loaders import Book

HEADER = """\
# Appendix A — Exam vs current platform

The exam guide (version {guide}) was written for the platform of early 2025. This table lists every
place where the exam's wording and today's Databricks platform (documentation snapshot
{snapshot}) differ, **what to answer on the exam**, and where the book explains it.

Generated by `uv run db-ml-associate book render-appendix-a` from
[`exam/platform-changes.yaml`](exam/platform-changes.yaml) — edit that file, not this page.

| Exam term | Current platform | Change | What the exam expects | Objectives | Explained in | Sources |
|---|---|---|---|---|---|---|
"""


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def render_appendix_a(book: Book) -> str:
    """Return the Markdown of Appendix A."""
    urls = {reference.id: reference.url for reference in book.references}
    guide = book.guide.version.isoformat() if book.guide else "unknown"
    snapshot = book.runtime.docs_snapshot.isoformat() if book.runtime else "unknown"
    lines = [HEADER.format(guide=guide, snapshot=snapshot).rstrip("\n")]
    for change in book.platform_changes:
        sources = ", ".join(f"[{ref}]({urls[ref]})" if ref in urls else ref for ref in change.references)
        chapters = ", ".join(
            f"[ch. {chapter.number}]({chapter.name})"
            for chapter in book.chapters
            if set(chapter.objectives) & set(change.objectives)
        )
        lines.append(
            f"| {_cell(change.exam_term)} | {_cell(change.current_term)} | {change.change} "
            f"| {_cell(change.exam_expects)} | {', '.join(change.objectives)} | {chapters or '—'} | {sources} |"
        )
    return "\n".join(lines) + "\n"
