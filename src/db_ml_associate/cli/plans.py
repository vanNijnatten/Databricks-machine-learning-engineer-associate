"""Render Appendix C (study plans) from ``book/plans/*.yaml`` with computed daily minutes."""

from db_ml_associate.content.loaders import Book
from db_ml_associate.content.models import PlanItem, StudyPlan
from db_ml_associate.content.plans import day_minutes, item_minutes

TRACK_ORDER = ("standard", "fast")
TRACK_TITLES = {
    "standard": "21-day standard plan",
    "fast": "14-day fast track",
}

HEADER = """\
# Appendix C — Study plans

Two plans take you from the introduction to both practice exams. Both follow the **recommended reading
order** — foundations first, so that every chapter's prerequisites come before it:

> Introduction → 1 → 6 → 7 → 8 → 9 → 11 → 10 → 4 → 2 → 3 → 5 → 12 → 13 → practice exams

Minutes are estimates computed from each chapter's reading time, its review questions (2 minutes
each) and its tutorial; a practice exam counts 90 minutes plus 45 minutes for reviewing the answers,
a weak-area review or an appendix revision 45 minutes. Optional activities are not counted. If you fall
behind, move a day rather than skipping the practice exams: book the exam only when you score at least
80 % in every section of both.

Generated by `uv run db-ml-associate book render-plans` from [`plans/`](plans/) — edit those files,
not this page.
"""


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _appendix_link(book: Book, letter: str) -> str:
    match = sorted(book.book_dir.glob(f"appendix-{letter.lower()}-*.md"))
    return f"[Appendix {letter.upper()}]({match[0].name})" if match else f"Appendix {letter.upper()}"


def _item_text(item: PlanItem, book: Book) -> str:
    """A Markdown description of one activity with a link to its page or notebook."""
    if item.kind == "introduction":
        text = "[Introduction](introduction.md)"
    elif item.kind == "chapter":
        chapter = book.chapter(int(item.target)) if item.target.isdigit() else None
        text = f"[Chapter {chapter.number}: {chapter.title}]({chapter.name})" if chapter else f"Chapter {item.target}"
    elif item.kind == "tutorial":
        owner = next((c for c in book.chapters if c.tutorial and c.tutorial.notebook == item.target), None)
        label = f"Tutorial {owner.number}" if owner else "Tutorial"
        text = f"[{label}](../{item.target})"
    elif item.kind == "exam":
        text = (
            f"Practice exam {item.target} ({_appendix_link(book, 'D')}, or `db-ml-associate exam take {item.target}`)"
        )
    elif item.kind == "appendix":
        text = f"Revise with {_appendix_link(book, item.target)}"
    else:
        text = f"Review: {_cell(item.target)}"
    if item.optional:
        text += f" (optional, {item_minutes(item, book)} min)"
    return text


def _render_plan(plan: StudyPlan, book: Book) -> list[str]:
    minutes = [day_minutes(day, book) for day in plan.days]
    total = sum(minutes)
    average = total / len(minutes) if minutes else 0
    lines = [
        f"## {TRACK_TITLES.get(plan.track, plan.track)}",
        "",
        f"{len(plan.days)} days · {total / 60:.1f} hours in total · on average {average:.0f} minutes a day.",
        "",
        "| Day | Goals | Activities | Minutes | Self-check |",
        "|---|---|---|---|---|",
    ]
    for day, day_total in zip(plan.days, minutes, strict=True):
        activities = "<br>".join(_item_text(item, book) for item in day.items)
        goals = "; ".join(_cell(goal) for goal in day.goals)
        lines.append(f"| {day.day} | {goals} | {activities} | {day_total} | {_cell(day.self_check)} |")
    return lines


def render_plans(book: Book) -> str:
    """Return the Markdown of Appendix C: one table per track, the standard plan first."""
    plans = sorted(
        book.plans,
        key=lambda plan: TRACK_ORDER.index(plan.track) if plan.track in TRACK_ORDER else len(TRACK_ORDER),
    )
    lines = [HEADER.rstrip("\n")]
    for plan in plans:
        lines.extend(["", *_render_plan(plan, book)])
    return "\n".join(lines) + "\n"
